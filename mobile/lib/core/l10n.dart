import 'package:flutter/widgets.dart';

/// UI languages. Arabic switches the whole app to right-to-left.
enum AppLang { fr, en, ar }

extension AppLangX on AppLang {
  Locale get locale => Locale(name);
  bool get isRtl => this == AppLang.ar;
  String get label => switch (this) {
        AppLang.fr => 'Français',
        AppLang.en => 'English',
        AppLang.ar => 'العربية',
      };
  String get short => name.toUpperCase();
  String get flagCountry => switch (this) {
        AppLang.fr => 'FR',
        AppLang.en => 'GB',
        AppLang.ar => 'DZ',
      };
}

